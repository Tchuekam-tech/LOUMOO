/**
 * LOUMOO — the compiled app's <head> comes from its source
 * ---------------------------------------------------------------------------
 * Commerce App.dc.html is a build output of build_redesign.py. The SEO work
 * added seoModel.js and the prerender styles to the compiled file by hand,
 * never to the source, so the next `npm run build:frontend` silently dropped
 * the head sync on SPA navigation and left the crawler fallback visible over
 * the app. Every script, stylesheet and style rule in the compiled <head> must
 * exist in the source that generates it.
 */

require('../setup');

const assert = require('assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '../..');
const compiled = fs.readFileSync(path.join(ROOT, 'Commerce App.dc.html'), 'utf8');
const source = fs.readFileSync(path.join(ROOT, 'build_redesign.py'), 'utf8');

const head = compiled.slice(0, compiled.indexOf('</head>'));
assert.ok(head.length > 0, 'the compiled app has a <head>');

const scripts = [...head.matchAll(/<script\b[^>]*\bsrc="([^"]+)"/g)].map((m) => m[1]);
const styles = [...head.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"/g)].map((m) => m[1]);
assert.ok(scripts.length > 5, 'the head loads its scripts');

const missing = [...scripts, ...styles].filter((ref) => !source.includes(ref));
assert.deepStrictEqual(missing, [], 'every <head> script and stylesheet is generated by build_redesign.py');

// Inline style rules: compare selectors, so a rule added only to the output is caught.
const inlineCss = [...head.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join('\n');
const selectors = [...inlineCss.matchAll(/^\s*([^{}\n/*@][^{}\n]*)\{/gm)].map((m) => m[1].trim());
const missingRules = selectors.filter((sel) => !source.includes(sel));
assert.deepStrictEqual(missingRules, [], 'every inline <head> style rule is generated by build_redesign.py');

console.log(`build_head_in_sync: ${scripts.length} scripts, ${styles.length} stylesheets, ${selectors.length} inline rules all come from the source`);
process.exit(0);
